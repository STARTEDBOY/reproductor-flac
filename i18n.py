def set_language(code: str) -> None:
    """Activa el idioma indicado; ignora códigos desconocidos."""
    global _current
    if code in TRANSLATIONS:
        _current = code


def get_language() -> str:
    return _current


def language_name(code: str | None = None) -> str:
    code = code or _current
    for language_code, name in LANGUAGES:
        if language_code == code:
            return name
    return code


def tr(key: str, **kwargs: object) -> str:
    """Devuelve el texto traducido de ``key`` en el idioma activo.

    Si el idioma activo no tiene la clave se usa el español y, como último
    recurso, se devuelve la propia clave.
    """
    text = TRANSLATIONS.get(_current, {}).get(key)
    if text is None:
        text = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text
